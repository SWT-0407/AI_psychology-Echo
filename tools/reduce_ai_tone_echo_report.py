def set_paragraph_text(paragraph, text: str) -> None:
    """Replace paragraph text while keeping the paragraph style."""
    if paragraph.runs:
        paragraph.runs[0].text = text
        for run in paragraph.runs[1:]:
            run.text = ""
    else:
        paragraph.add_run(text)


